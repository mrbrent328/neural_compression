"""
TEST10 — CAUSAL NEURAL PROBABILITY / RANGE-CODED SOURCE COMPRESSION

Follow-up to TEST9.

The major architectural change is that the predictor no longer
selects a single "best" byte and stores a residual.

Instead:

    context
        ↓
    neural probability distribution
        ↓
    probability of ACTUAL byte
        ↓
    arithmetic/range coder
        ↓
    compressed bitstream

The encoder and decoder are strictly causal.

IMPORTANT:

The encoder is NOT allowed to use the original held-out bytes as
context when generating predictions.

Instead, the encoder maintains a simulated reconstruction buffer:

    training prefix
          +
    previously encoded actual bytes

The decoder maintains the exact same state:

    training prefix
          +
    previously decoded bytes

Therefore the probability distribution generated by the encoder
and decoder is identical at every position.

EXPERIMENTAL RULES

- First 75% of each dataset is training data.
- Final 25% is completely held out.
- Held-out bytes are NEVER used to train the neural model.
- Predictive encoders may only use causal context.
- Every predictive method must reconstruct held-out bytes exactly.
- SHA-256 validation is mandatory.
- Model size + compressed payload + metadata are counted.
- Every scaling point receives its own neural model.
- No floating-point probability representation is stored.
- Probabilities are converted to deterministic integer frequencies.
- Decoder uses the exact same model and deterministic frequency table.

METHODS

1. zlib full-file baseline

2. TEST9 neural residual + zlib
   Causal neural argmax prediction.

3. Neural probability model + range coder

4. Character/context probability model + range coder

5. Neural + context probability mixture + range coder

The primary experiment is METHOD 3.

GPU

Designed for AMD ROCm PyTorch.

Launch with:

    HSA_OVERRIDE_GFX_VERSION=10.3.0 python3 test10.py

The override belongs in the shell environment.

The neural network remains resident on the GPU.

Training and probability inference are batched where practical.

Range encoding itself is CPU-side because the arithmetic coder is
sequential and operates on the exact probability distribution.

CAUSALITY PRINCIPLE

At held-out byte N, both encoder and decoder know exactly:

    training prefix
    +
    bytes 0 ... N-1 of the held-out stream

Neither side may inspect byte N+1 or any future original byte.

The encoder therefore simulates the decoder's state by appending
the known actual byte after encoding it.

This is deliberately redundant computation: correctness and
scientific validity are more important than encoder speed.

"""

