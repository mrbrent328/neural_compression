def make_neural_training_samples(
    data,
    train_end,
    boundaries,
    context_size,
    sample_count
):
    eligible_count = 0

    for boundary in boundaries:

        start = boundary["start"]

        end = min(
            boundary["end"],
            train_end
        )

        if (
            end - start
            > context_size
        ):
            eligible_count += (
                end
                - start
                - context_size
            )

    if eligible_count <= 0:
        raise RuntimeError(
            "Not enough training data "
            "for neural model."
        )

    rng = np.random.default_rng(
        RANDOM_SEED
    )

    sample_count = min(
        sample_count,
        eligible_count
    )

    chosen = np.sort(
        rng.choice(
            eligible_count,
            size=sample_count,
            replace=False
        )
    )

    X = np.empty(
        (
            sample_count,
            context_size
        ),
        dtype=np.int64
    )

    y = np.empty(
        sample_count,
        dtype=np.int64
    )

    chosen_index = 0
    cumulative = 0

    for boundary in boundaries:

        start = boundary["start"]

        end = min(
            boundary["end"],
            train_end
        )

        count = (
            end
            - start
            - context_size
        )

        if count <= 0:
            continue

        lower = cumulative

        upper = (
            cumulative
            + count
        )

        while (
            chosen_index < sample_count
            and chosen[chosen_index] < upper
        ):

            ordinal = int(
                chosen[chosen_index]
            )

            pos = (
                start
                + context_size
                + (
                    ordinal
                    - lower
                )
            )

            X[chosen_index] = np.frombuffer(
                data[
                    pos - context_size:
                    pos
                ],
                dtype=np.uint8
            )

            y[chosen_index] = data[pos]

            chosen_index += 1

        cumulative = upper

        if chosen_index >= sample_count:
            break

    return X, y


