def save_manifest(
    files,
    root,
    corpus_size
):
    manifest = []

    for path in files:

        try:
            size = path.stat().st_size
        except OSError:
            size = None

        manifest.append({

            "path":
                str(
                    path.relative_to(root)
                ),

            "size":
                size,
        })

    obj = {

        "root":
            str(root),

        "file_count":
            len(files),

        "corpus_size":
            corpus_size,

        "files":
            manifest,
    }

    with open(
        "test10_manifest.json",
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            obj,
            f,
            indent=2
        )


