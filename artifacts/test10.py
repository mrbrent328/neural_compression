def read_file(path):
    with open(path, "rb") as f:
        return f.read()


def build_corpus(
    files,
    root,
    target_size=None
):
    chunks = []
    boundaries = []

    total = 0

    for path in files:

        try:
            data = read_file(path)
        except Exception as e:
            print(
                f"Could not read {path}: {e}"
            )
            continue

        if not data:
            continue

        if target_size is not None:

            remaining = (
                target_size
                - total
            )

            if remaining <= 0:
                break

            if len(data) > remaining:
                data = data[:remaining]

        start = total
        end = total + len(data)

        chunks.append(data)

        boundaries.append({
            "path": str(
                path.relative_to(root)
            ),
            "start": start,
            "end": end,
            "size": len(data),
        })

        total = end

        if (
            target_size is not None
            and total >= target_size
        ):
            break

    return (
        b"".join(chunks),
        boundaries
    )


def build_boundary_set(boundaries):
    starts = {0}

    for boundary in boundaries:
        starts.add(
            boundary["start"]
        )

    return starts


