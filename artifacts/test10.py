class RangeEncoder:

    def __init__(
        self,
        total_frequency=TOTAL_FREQUENCY
    ):
        self.total_frequency = (
            total_frequency
        )

        self.low = 0

        self.high = (
            (1 << CODE_BITS) - 1
        )

        self.output = bytearray()

    def output_byte(self, value):
        self.output.append(
            value & 0xFF
        )

    def encode_symbol(
        self,
        symbol,
        frequencies
    ):
        cumulative = np.cumsum(
            frequencies
        )

        low_count = (
            0
            if symbol == 0
            else int(
                cumulative[
                    symbol - 1
                ]
            )
        )

        high_count = int(
            cumulative[symbol]
        )

        range_width = (
            self.high
            - self.low
            + 1
        )

        self.high = (
            self.low
            + (
                range_width
                * high_count
                // self.total_frequency
            )
            - 1
        )

        self.low = (
            self.low
            + (
                range_width
                * low_count
                // self.total_frequency
            )
        )

        while True:

            if (
                (self.high & 0xFF000000)
                == (self.low & 0xFF000000)
            ):

                self.output_byte(
                    self.high >> 24
                )

                self.low = (
                    self.low << 8
                ) & 0xFFFFFFFF

                self.high = (
                    (
                        self.high << 8
                    )
                    & 0xFFFFFFFF
                ) | 0xFF

            elif (
                self.low & 0x80000000
                and not (
                    self.high
                    & 0x80000000
                )
            ):

                self.low = (
                    (
                        self.low
                        ^ 0x40000000
                    )
                    << 1
                ) & 0xFFFFFFFF

                self.high = (
                    (
                        self.high
                        ^ 0x40000000
                    )
                    << 1
                ) & 0xFFFFFFFF

                self.high |= 1

            else:
                break

    def finish(self):

        for _ in range(
            CODE_BITS // 8
        ):
            self.output_byte(
                self.low >> 24
            )

            self.low = (
                self.low << 8
            ) & 0xFFFFFFFF

        return bytes(self.output)


class RangeDecoder:

    def __init__(
        self,
        data,
        total_frequency=TOTAL_FREQUENCY
    ):
        self.data = data
        self.position = 0

        self.total_frequency = (
            total_frequency
        )

        self.low = 0

        self.high = (
            (1 << CODE_BITS) - 1
        )

        self.code = 0

        for _ in range(
            CODE_BITS // 8
        ):
            self.code = (
                (
                    self.code << 8
                )
                | self.read_byte()
            )

    def read_byte(self):

        if self.position >= len(self.data):
            return 0

        value = self.data[
            self.position
        ]

        self.position += 1

        return value

    def decode_symbol(
        self,
        frequencies
    ):
        cumulative = np.cumsum(
            frequencies
        )

        range_width = (
            self.high
            - self.low
            + 1
        )

        value = (
            (
                (
                    self.code
                    - self.low
                    + 1
                )
                * self.total_frequency
                - 1
            )
            // range_width
        )

        symbol = int(
            np.searchsorted(
                cumulative,
                value,
                side="right"
            )
        )

        if symbol >= 256:
            symbol = 255

        low_count = (
            0
            if symbol == 0
            else int(
                cumulative[
                    symbol - 1
                ]
            )
        )

        high_count = int(
            cumulative[symbol]
        )

        self.high = (
            self.low
            + (
                range_width
                * high_count
                // self.total_frequency
            )
            - 1
        )

        self.low = (
            self.low
            + (
                range_width
                * low_count
                // self.total_frequency
            )
        )

        while True:

            if (
                (self.high & 0xFF000000)
                == (self.low & 0xFF000000)
            ):

                self.low = (
                    self.low << 8
                ) & 0xFFFFFFFF

                self.high = (
                    (
                        self.high << 8
                    )
                    & 0xFFFFFFFF
                ) | 0xFF

                self.code = (
                    (
                        self.code << 8
                    )
                    & 0xFFFFFFFF
                ) | self.read_byte()

            elif (
                self.low & 0x80000000
                and not (
                    self.high
                    & 0x80000000
                )
            ):

                self.low = (
                    (
                        self.low
                        ^ 0x40000000
                    )
                    << 1
                ) & 0xFFFFFFFF

                self.high = (
                    (
                        self.high
                        ^ 0x40000000
                    )
                    << 1
                ) & 0xFFFFFFFF

                self.high |= 1

                self.code = (
                    (
                        self.code
                        ^ 0x40000000
                    )
                    << 1
                ) & 0xFFFFFFFF

                self.code |= self.read_byte()

            else:
                break

        return symbol


# ============================================================
# GLOBAL BYTE MODEL
# ============================================================

def train_global_distribution(
    data,
    train_end
):
    counts = np.ones(
        256,
        dtype=np.float64
    )

    counts += np.bincount(
        np.frombuffer(
            data[:train_end],
            dtype=np.uint8
        ),
        minlength=256
    )

    return (
        counts
        / counts.sum()
    )


# ============================================================
# CONTEXT MODEL
# ============================================================

def train_context_model(
    data,
    train_end,
    boundaries,
    context_size
):
    counts = defaultdict(Counter)

    for boundary in boundaries:

        start = boundary["start"]

        end = min(
            boundary["end"],
            train_end
        )

        if (
            end - start
            <= context_size
        ):
            continue

        local = data[
            start:end
        ]

        for i in range(
            context_size,
            len(local)
        ):

            context = tuple(
                local[
                    i - context_size:i
                ]
            )

            counts[context][
                local[i]
            ] += 1

    return counts


def estimate_context_model_size(
    context_counts
):
    if not context_counts:
        return 0

    entries = 0

    for context, counter in (
        context_counts.items()
    ):
        entries += (
            len(context)
            + 8
            + (
                len(counter)
                * 4
            )
        )

    return entries


def context_probability_model(
    context_counts,
    context
):
    counter = context_counts.get(
        tuple(context)
    )

    if counter is None:

        return np.ones(
            256,
            dtype=np.float64
        ) / 256.0

    probabilities = np.ones(
        256,
        dtype=np.float64
    )

    for symbol, count in counter.items():
        probabilities[symbol] += count

    probabilities /= (
        probabilities.sum()
    )

    return probabilities


# ============================================================
# NEURAL PROBABILITY
# ============================================================

@torch.no_grad()
def neural_probability(
    model,
    context_bytes
):
    """
    Generate the neural probability distribution for exactly
    one causal context.
    """

    context = np.frombuffer(
        context_bytes,
        dtype=np.uint8
    ).astype(np.int64)

    tensor = (
        torch.from_numpy(context)
        .reshape(1, CONTEXT_SIZE)
        .to(
            DEVICE,
            dtype=torch.long
        )
    )

    logits = model(tensor)

    probabilities = (
        torch.softmax(
            logits,
            dim=1
        )
        .cpu()
        .numpy()[0]
    )

    del tensor
    del logits

    return probabilities


@torch.no_grad()
def neural_probability_batches(
    model,
    contexts
):
    model.eval()

    if not contexts:
        return np.empty(
            (0, 256),
            dtype=np.float64
        )

    probabilities = []

    gpu_sync()

    start_time = time.time()

    for offset in range(
        0,
        len(contexts),
        PREDICTION_BATCH
    ):

        batch = contexts[
            offset:
            offset + PREDICTION_BATCH
        ]

        X = np.empty(
            (
                len(batch),
                CONTEXT_SIZE
            ),
            dtype=np.int64
        )

        for row, context in enumerate(batch):
            X[row] = np.frombuffer(
                context,
                dtype=np.uint8
            )

        tensor = (
            torch.from_numpy(X)
            .to(
                DEVICE,
                dtype=torch.long
            )
        )

        logits = model(tensor)

        probs = (
            torch.softmax(
                logits,
                dim=1
            )
            .cpu()
            .numpy()
        )

        probabilities.append(probs)

        del X
        del tensor
        del logits

    gpu_sync()

    elapsed = (
        time.time()
        - start_time
    )

    result = np.concatenate(
        probabilities,
        axis=0
    )

    print(
        f"Neural probability inference: "
        f"{len(contexts):,} samples "
        f"in {elapsed:.2f}s"
    )

    return result


# ============================================================
# MIXTURE
# ============================================================

def mixed_probability(
    neural_probabilities,
    context_probabilities,
    neural_weight=0.75
):
    mixed = (
        neural_weight
        * neural_probabilities
        +
        (1.0 - neural_weight)
        * context_probabilities
    )

    mixed /= mixed.sum()

    return mixed


# ============================================================
# CAUSAL CONTEXT HELPER
# ============================================================

def causal_context(
    reconstructed,
    global_index,
    boundary_starts
):
    """
    Return the exact context available to BOTH encoder and
    decoder.

    reconstructed contains:

        training prefix
        +
        already reconstructed/known bytes

    It MUST NOT contain future bytes.
    """

    if global_index in boundary_starts:
        return None

    start = (
        global_index
        - CONTEXT_SIZE
    )

    if start < 0:
        return None

    return bytes(
        reconstructed[
            start:
            global_index
        ]
    )


