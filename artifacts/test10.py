class NeuralPredictor(nn.Module):

    def __init__(
        self,
        context_size=4,
        embed_size=32,
        hidden_size=128
    ):
        super().__init__()

        self.context_size = context_size

        self.embedding = nn.Embedding(
            256,
            embed_size
        )

        self.fc1 = nn.Linear(
            context_size * embed_size,
            hidden_size
        )

        self.fc2 = nn.Linear(
            hidden_size,
            256
        )

        self.activation = nn.ReLU()

    def forward(self, x):

        x = self.embedding(x)

        x = x.reshape(
            x.shape[0],
            -1
        )

        x = self.activation(
            self.fc1(x)
        )

        return self.fc2(x)


def neural_model_size(model):
    return sum(
        tensor.numel()
        * tensor.element_size()
        for tensor in model.state_dict().values()
    )


