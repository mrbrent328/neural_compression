# ============================================================

def probabilities_to_frequencies(
    probabilities,
    total_frequency=TOTAL_FREQUENCY,
    minimum_frequency=MIN_FREQUENCY
):
    """
    Convert floating-point probabilities into deterministic
    integer frequencies.

    Returned frequencies ALWAYS sum to total_frequency.

    Floating-point probabilities are never stored in the
    compressed representation.
    """

    probabilities = np.asarray(
        probabilities,
        dtype=np.float64
    )

    probabilities = np.maximum(
        probabilities,
        0.0
    )

    probability_sum = (
        probabilities.sum()
    )

    if (
        not np.isfinite(probability_sum)
        or probability_sum <= 0
    ):
        probabilities = np.ones(
            256,
            dtype=np.float64
        ) / 256.0

    else:
        probabilities /= probability_sum

    available_frequency = (
        total_frequency
        - 256 * minimum_frequency
    )

    raw = (
        probabilities
        * available_frequency
    )

    frequencies = np.floor(
        raw
    ).astype(np.int64)

    frequencies += minimum_frequency

    current = int(
        frequencies.sum()
    )

    difference = (
        total_frequency
        - current
    )

    if difference > 0:

        fractional = (
            raw
            - np.floor(raw)
        )

        order = np.argsort(
            fractional
        )[::-1]

        for index in order[:difference]:
            frequencies[index] += 1

    elif difference < 0:

        excess = -difference

        order = np.argsort(
            frequencies
        )[::-1]

        for index in order:

            removable = (
                frequencies[index]
                - minimum_frequency
            )

            if removable <= 0:
                continue

            amount = min(
                removable,
                excess
            )

            frequencies[index] -= amount

            excess -= amount

            if excess <= 0:
                break

    if int(frequencies.sum()) != total_frequency:
        raise RuntimeError(
            "Probability quantization failed."
        )

    return frequencies.astype(np.int64)


