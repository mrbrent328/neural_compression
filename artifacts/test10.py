# NEURAL RANGE ENCODER
# ============================================================

def neural_range_encode(
    model,
    data,
    train_end,
    boundaries
):
    """
    STRICTLY CAUSAL neural range encoder.

    The original data is used ONLY to obtain the actual symbol
    being encoded.

    Context comes exclusively from `reconstructed`.
    """

    heldout = data[
        train_end:
    ]

    if not heldout:
        return b"", {}

    encoder = RangeEncoder(
        TOTAL_FREQUENCY
    )

    reconstructed = bytearray(
        data[:train_end]
    )

    boundary_starts = (
        build_boundary_set(
            boundaries
        )
    )

    total_bits = 0.0
    predicted_bytes = 0

    model.eval()

    gpu_sync()

    start_time = time.time()

    for i in range(
        len(heldout)
    ):

        global_index = (
            train_end
            + i
        )

        context = causal_context(
            reconstructed,
            global_index,
            boundary_starts
        )

        if context is None:

            probabilities = (
                np.ones(
                    256,
                    dtype=np.float64
                )
                / 256.0
            )

        else:

            probabilities = (
                neural_probability(
                    model,
                    context
                )
            )

        actual = data[
            global_index
        ]

        actual_probability = max(
            float(
                probabilities[actual]
            ),
            1e-12
        )

        total_bits += (
            -math.log2(
                actual_probability
            )
        )

        frequencies = (
            probabilities_to_frequencies(
                probabilities
            )
        )

        encoder.encode_symbol(
            actual,
            frequencies
        )

        # CRITICAL:
        # This is what makes the encoder causal.
        reconstructed.append(
            actual
        )

        predicted_bytes += 1

        if (
            predicted_bytes
            % 100_000
            == 0
        ):
            print(
                f"  Encoded "
                f"{predicted_bytes:,}/"
                f"{len(heldout):,}",
                end="\r",
                flush=True
            )

    gpu_sync()

    elapsed = (
        time.time()
        - start_time
    )

    print()

    encoded = encoder.finish()

    cross_entropy = (
        total_bits / predicted_bytes
        if predicted_bytes
        else 0.0
    )

    print(
        f"Neural range encoding: "
        f"{len(heldout):,} bytes "
        f"in {elapsed:.2f}s"
    )

    print(
        f"Theoretical cross entropy: "
        f"{cross_entropy:.4f} bits/byte"
    )

    print(
        f"Actual range-coded payload: "
        f"{len(encoded):,} bytes"
    )

    return encoded, {
        "cross_entropy_bits":
            cross_entropy,

        "theoretical_bits":
            total_bits,

        "predicted_bytes":
            predicted_bytes,
    }


