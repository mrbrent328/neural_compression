def format_bytes(n):
    if n < 1024:
        return f"{n:,} B"

    if n < 1024 ** 2:
        return f"{n / 1024:.2f} KB"

    if n < 1024 ** 3:
        return f"{n / (1024 ** 2):.2f} MB"

    return f"{n / (1024 ** 3):.2f} GB"


def entropy_bytes(data):
    if not data:
        return 0.0

    arr = np.frombuffer(
        data,
        dtype=np.uint8
    )

    counts = np.bincount(
        arr,
        minlength=256
    )

    probabilities = (
        counts[counts > 0]
        / len(arr)
    )

    return float(
        -np.sum(
            probabilities
            * np.log2(probabilities)
        )
    )


