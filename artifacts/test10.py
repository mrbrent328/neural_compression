# ============================================================
# RANGE METHOD VERIFICATION
# ============================================================

def evaluate_range_method(
    encoded,
    decoder_function,
    heldout,
    heldout_hash,
    method_name
):
    print()
    print(
        f"Verifying {method_name}..."
    )

    reconstructed = (
        decoder_function()
    )

    reconstructed_hash = sha256(
        reconstructed
    )

    exact = (
        reconstructed
        == heldout
    )

    hash_match = (
        reconstructed_hash
        == heldout_hash
    )

    print(
        f"Expected SHA256: "
        f"{heldout_hash}"
    )

    print(
        f"Actual SHA256:   "
        f"{reconstructed_hash}"
    )

    print(
        f"Exact:           "
        f"{exact}"
    )

    print(
        f"Hash match:      "
        f"{hash_match}"
    )

    if not exact or not hash_match:

        # Find the first differing byte to make failures useful.
        first_difference = None

        limit = min(
            len(reconstructed),
            len(heldout)
        )

        for i in range(limit):

            if (
                reconstructed[i]
                != heldout[i]
            ):
                first_difference = i
                break

        if first_difference is None:
            first_difference = limit

        print(
            f"First differing offset: "
            f"{first_difference:,}"
        )

        if (
            first_difference
            < len(heldout)
            and first_difference
            < len(reconstructed)
        ):
            print(
                f"Expected byte: "
                f"{heldout[first_difference]}"
            )

            print(
                f"Actual byte:   "
                f"{reconstructed[first_difference]}"
            )

        raise RuntimeError(
            f"{method_name} failed "
            f"exact reconstruction."
        )

    return True


