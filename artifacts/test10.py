def print_summary(rows):

    print()
    print("=" * 70)
    print("GLOBAL SUMMARY")
    print("=" * 70)

    if not rows:

        print(
            "No results."
        )

        return

    datasets = sorted(
        set(
            r["dataset_size"]
            for r in rows
        )
    )

    methods = [
        "zlib",
        "test9_neural_residual",
        "neural_range",
        "hybrid_probability",
    ]

    print()
    print(
        f"{'SIZE':<12}"
        f"{'ZLIB':>14}"
        f"{'TEST9':>14}"
        f"{'NEURAL':>14}"
        f"{'HYBRID':>14}"
    )

    for size in datasets:

        subset = [
            r
            for r in rows
            if r["dataset_size"] == size
        ]

        values = {}

        for method in methods:

            match = next(
                (
                    r
                    for r in subset
                    if r["method"] == method
                ),
                None
            )

            values[method] = (
                match["total_size"]
                if match
                else None
            )

        def fmt(value):

            if value is None:
                return "N/A"

            return f"{value:,}"

        print(
            f"{size:<12,}"
            f"{fmt(values['zlib']):>14}"
            f"{fmt(values['test9_neural_residual']):>14}"
            f"{fmt(values['neural_range']):>14}"
            f"{fmt(values['hybrid_probability']):>14}"
        )

    print()
    print(
        "BREAK-EVEN"
    )

    for method in methods:

        if method == "zlib":
            continue

        winning = [
            r
            for r in rows
            if r["method"] == method
            and r["total_size"]
            < r["zlib_size"]
        ]

        if winning:

            first = min(
                winning,
                key=lambda r:
                r["dataset_size"]
            )

            print(
                f"{method:<24}: "
                f"{format_bytes(first['dataset_size'])}"
            )

        else:

            print(
                f"{method:<24}: "
                f"not observed"
            )

    print()
    print(
        "INFORMATION GAIN"
    )

    for size in datasets:

        subset = [
            r
            for r in rows
            if r["dataset_size"] == size
        ]

        print()
        print(
            format_bytes(size)
        )

        for row in subset:

            if row[
                "cross_entropy_bits"
            ] is None:
                continue

            print(
                f"  "
                f"{row['method']:<24}"
                f"{row['cross_entropy_bits']:.4f}"
                f" bits/byte"
            )

    print()
    print(
        "BEST AT EACH SIZE"
    )

    for size in datasets:

        subset = [
            r
            for r in rows
            if r["dataset_size"] == size
        ]

        best = min(
            subset,
            key=lambda r:
            r["total_size"]
        )

        print(
            f"{format_bytes(size):>12}: "
            f"{best['method']:<24}"
            f"{format_bytes(best['total_size'])}"
            f" "
            f"({best['improvement_percent']:.2f}% "
            f"vs zlib)"
        )


